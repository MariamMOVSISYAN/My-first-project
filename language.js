// Remove extra spaces and line breaks when matching text.
function normalize(text) {
  return text.replace(/\s+/g, " ").trim();
}

// Save the original English text so switching back works.
const textItems = [];

const walker = document.createTreeWalker(
  document.body,
  NodeFilter.SHOW_TEXT,
  {
    acceptNode(node) {
      const parent = node.parentElement;

      if (!parent || parent.closest("script, style, select")) {
        return NodeFilter.FILTER_REJECT;
      }

      const original = normalize(node.nodeValue);

      return Object.prototype.hasOwnProperty.call(translations, original)
        ? NodeFilter.FILTER_ACCEPT
        : NodeFilter.FILTER_REJECT;
    }
  }
);

while (walker.nextNode()) {
  textItems.push({
    node: walker.currentNode,
    original: walker.currentNode.nodeValue,
    key: normalize(walker.currentNode.nodeValue)
  });
}

// Save placeholders separately.
const placeholderItems = Array.from(
  document.querySelectorAll("[placeholder]")
).map(function (element) {
  return {
    element: element,
    original: element.getAttribute("placeholder")
  };
});

const languageSelect = document.getElementById("language-select");
const statusElement = document.getElementById("form-status");

let currentLanguage = "en";

function changeLanguage(language) {
  currentLanguage = language === "hy" ? "hy" : "en";

  document.documentElement.lang = currentLanguage;
  languageSelect.value = currentLanguage;

  textItems.forEach(function (item) {
    item.node.nodeValue =
      currentLanguage === "hy"
        ? " " + translations[item.key] + " "
        : item.original;
  });

  placeholderItems.forEach(function (item) {
    item.element.setAttribute(
      "placeholder",
      currentLanguage === "hy"
        ? translations[item.original] || item.original
        : item.original
    );
  });

  document.title =
    currentLanguage === "hy"
      ? "Positivus — Թվային մարքեթինգ"
      : "Positivus — Digital Marketing";

  document.querySelector('meta[name="description"]').content =
    currentLanguage === "hy"
      ? "Positivus թվային մարքեթինգի ծառայություններ։"
      : "Positivus digital marketing services.";

  document.querySelectorAll("nav").forEach(function (nav, index) {
    nav.setAttribute(
      "aria-label",
      currentLanguage === "hy"
        ? (index === 0 ? "Հիմնական նավարկում" : "Էջատակի նավարկում")
        : (index === 0 ? "Main navigation" : "Footer navigation")
    );
  });

  languageSelect.setAttribute(
    "aria-label",
    currentLanguage === "hy" ? "Կայքի լեզուն" : "Website language"
  );

  const partners = document.querySelector(".partners");

  if (partners) {
    partners.setAttribute(
      "aria-label",
      currentLanguage === "hy"
        ? "Դիզայնում ներկայացված ապրանքանիշեր"
        : "Brands shown in the design"
    );
  }

  // Translate the form status if it is already visible.
  if (statusElement.textContent.trim()) {
    updateFormStatus();
  }

  try {
    localStorage.setItem("website-language", currentLanguage);
  } catch (error) {
    // Switching still works if the browser blocks storage.
  }
}

function updateFormStatus() {
  const englishMessage =
    "This is a practice form. Your message has not been sent.";

  statusElement.textContent =
    currentLanguage === "hy"
      ? translations[englishMessage]
      : englishMessage;
}

languageSelect.addEventListener("change", function () {
  changeLanguage(languageSelect.value);
});

// Runs after your existing form handler and translates its message.
document.getElementById("contact-form").addEventListener(
  "submit",
  function (event) {
    event.preventDefault();
    updateFormStatus();
  }
);

// Restore the previously selected language.
let savedLanguage = "en";

try {
  savedLanguage = localStorage.getItem("website-language") || "en";
} catch (error) {
  savedLanguage = "en";
}

changeLanguage(savedLanguage);